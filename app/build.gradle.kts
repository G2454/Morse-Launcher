// Release signing comes from environment variables so no secret ever lives in the repo.
// In CI these are filled from GitHub secrets (see .github/workflows/ci.yml).
val releaseKeystore: String? = System.getenv("MORSE_KEYSTORE_PATH")

android {
    namespace = "dev.morse.launcher"
    compileSdk = 35

    defaultConfig {
        applicationId = "dev.morse.launcher"
        minSdk = 29
        targetSdk = 35
        versionCode = (System.getenv("MORSE_VERSION_CODE") ?: "1").toInt()
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("MORSE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("MORSE_KEY_ALIAS")
                keyPassword = System.getenv("MORSE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = if (releaseKeystore != null) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all {
                it.testLogging {
                    events("failed", "skipped")
                    exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
                }
                it.maxHeapSize = "2g"
            }
        }
    }

    lint {
        // Lint runs in CI and its report is uploaded, but it does not fail the build.
        abortOnError = false
        checkReleaseBuilds = false
        htmlReport = true
        xmlReport = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

